import { chromium } from 'playwright-core';
const exe = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const browser = await chromium.launch({ executablePath: exe, headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 940 } });
const net = [];
page.on('response', (r) => { if (/pulls\/1/.test(r.url()) && r.request().method() === 'PATCH') net.push(r.status()); });
page.on('console', (m) => { if (m.type() === 'error' && !/favicon|404|401/.test(m.text())) console.log('CONSOLE-ERR:', m.text().slice(0, 200)); });
await page.goto('http://localhost:3099/?root=' + encodeURIComponent('/tmp/qa-pr-work'));
await page.waitForTimeout(3000);
await page.evaluate(() => { const b = [...document.querySelectorAll('button')].find(x => /Pull Requests/i.test(x.title || '')); if (b) b.click(); });
await page.waitForTimeout(2500);
await page.locator('text=qa: PR edit test').first().click();
await page.waitForTimeout(2500);
await page.evaluate(() => { const b = [...document.querySelectorAll('button')].find(x => x.textContent.trim() === 'Edit…'); if (b) b.click(); });
await page.waitForTimeout(800);
await page.locator('input:visible').first().fill('qa: PR edit test (UI-SAVE-WORKS)');
await page.locator('button:visible', { hasText: /^Save$/ }).first().click();
await page.waitForTimeout(3500);
console.log('PATCH statuses:', JSON.stringify(net));
const t = await page.evaluate(() => document.body.innerText);
console.log(/UI-SAVE-WORKS/.test(t) ? 'PASS UI save reflects new title' : 'FAIL UI save');
await browser.close();
